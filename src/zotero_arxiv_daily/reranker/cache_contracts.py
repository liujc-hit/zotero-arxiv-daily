"""Structural seams between ranking, built-in encoders and the optional store."""

from __future__ import annotations

from typing import TYPE_CHECKING, Literal, Protocol

import numpy as np
from omegaconf import DictConfig

if TYPE_CHECKING:
    from ..compute_cache import CacheStats, CacheValue, FloatArray, ScoreSnapshot


class CacheStore(Protocol):
    def make_key(self, kind: str, parts: CacheValue) -> str: ...
    def get_vector(self, key: str) -> FloatArray | None: ...
    def put_vector(self, key: str, array: FloatArray) -> None: ...
    def get_scores(self, key: str, candidate_count: int) -> ScoreSnapshot | None: ...
    def put_scores(self, key: str, snapshot: ScoreSnapshot) -> None: ...
    def flush(self) -> bool: ...
    def stats(self) -> CacheStats: ...


class RankingBackend(Protocol):
    config: DictConfig
    _compute_cache: CacheStore | None

    def _cache_backend(self) -> Literal["local", "api"] | None: ...
    def _cache_encode_options(self) -> str: ...
    def get_embeddings(self, texts: list[str]) -> np.ndarray: ...
